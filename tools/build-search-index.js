#!/usr/bin/env node
/* ==========================================================================
   Rebuilds js/search-index.js from the slides in labs/*.html.
   Optional maintenance tool: the site runs without it, but run it after
   adding or editing slides so the cross-lab search stays up to date.

     node tools/build-search-index.js

   Needs only Node.js (no npm packages). It also warns about duplicate slide
   ids and slides without a data-title.
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const LABS = path.join(ROOT, 'labs');
const OUT = path.join(ROOT, 'js', 'search-index.js');
const MAX_TEXT = 1200;

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', ndash: '–', mdash: '—', hellip: '…', rarr: '→', larr: '←', times: '×', divide: '÷', le: '≤', ge: '≥', ne: '≠' };
function decode(s) {
  return s.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, e) => {
    if (e[0] === '#') return String.fromCodePoint(e[1].toLowerCase() === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
    return ENTITIES[e.toLowerCase()] !== undefined ? ENTITIES[e.toLowerCase()] : m;
  });
}
function attr(tag, name) {
  const m = tag.match(new RegExp('\\s' + name + '="([^"]*)"'));
  return m ? decode(m[1]) : '';
}
function toText(html) {
  return decode(html
    .replace(/<aside class="notes"[\s\S]*?<\/aside>/g, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<[^>]+>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

const files = fs.readdirSync(LABS).filter(f => f.endsWith('.html') && !f.startsWith('_')).sort();
const entries = [];
let warnings = 0;

for (const f of files) {
  const html = fs.readFileSync(path.join(LABS, f), 'utf8');
  const bodyTag = (html.match(/<body[^>]*>/) || [''])[0];
  const page = attr(bodyTag, 'data-page') || f.replace(/\.html$/, '');
  const re = /<section\s+class="slide[^"]*"(?:"[^"]*"|[^>"])*>/g;
  const starts = [];
  let m;
  while ((m = re.exec(html)) !== null) starts.push({ idx: m.index, tag: m[0] });
  const seen = new Set();
  starts.forEach((s, i) => {
    const end = i + 1 < starts.length ? starts[i + 1].idx : html.indexOf('</main>', s.idx);
    const chunk = html.slice(s.idx + s.tag.length, end === -1 ? undefined : end);
    const id = attr(s.tag, 'id');
    const title = attr(s.tag, 'data-title');
    if (!id) { console.warn(`! ${f}: slide #${i + 1} has no id`); warnings++; }
    if (!title) { console.warn(`! ${f}: slide "${id}" has no data-title`); warnings++; }
    if (seen.has(id)) { console.warn(`! ${f}: duplicate slide id "${id}"`); warnings++; }
    seen.add(id);
    entries.push({ page, id, title: title || id, section: attr(s.tag, 'data-section'), text: toText(chunk).slice(0, MAX_TEXT) });
  });
  console.log(`${f.padEnd(20)} ${String(starts.length).padStart(3)} slides`);
}

const banner = '/* Generated by tools/build-search-index.js on ' + new Date().toISOString().slice(0, 10) +
  '. Do not edit by hand; rerun: node tools/build-search-index.js */\n';
fs.writeFileSync(OUT, banner + 'window.CPE104L_SEARCH = ' + JSON.stringify(entries) + ';\n');
console.log(`\nWrote ${path.relative(ROOT, OUT)}: ${entries.length} slides from ${files.length} pages` + (warnings ? `, ${warnings} warning(s)` : ''));
